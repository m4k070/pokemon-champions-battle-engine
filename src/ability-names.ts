const ABILITY_NAME_SET: ReadonlySet<string> = new Set(ABILITY_NAMES);

// 外部入力（MCPの技・ポケモン定義など）が既知の特性名かを検証する。
export function isAbilityName(value: string): value is AbilityName {
  return ABILITY_NAME_SET.has(value);
}
